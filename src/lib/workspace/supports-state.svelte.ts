import type { AutoSupportDiagnostics } from '$lib/supports/generate-auto-supports';
import { generateRaftPlan } from '$lib/supports/raft-plan';
import {
	AutoSupportBuild,
	type AutoSupportBuildInput,
	type AutoSupportOutcome
} from './auto-support-state.svelte';
import {
	generateSupportPlan,
	supportFootCenter,
	type ModelSurfaceHit,
	type SupportPoint
} from './supports';

/**
 * The editable support-point set and everything derived from it — the raft plan,
 * the renderable support plan, and the worker-backed first-draft auto-supports.
 * Cross-step reactions (e.g. rebuilding the preview when the draft lands) run
 * through the `onAutoApplied` callback the composition root supplies.
 */
export class SupportsState {
	points = $state.raw<SupportPoint[]>([]);
	autoDiagnostics = $state.raw<AutoSupportDiagnostics | null>(null);
	autoGeneratedCount = $state(0);
	autoBuild: AutoSupportBuild;

	raftPlan = $derived(
		generateRaftPlan(
			this.points
				.filter((point) => !point.lowerContactPosition)
				.map((point) => ({ id: point.id, center: supportFootCenter(point) }))
		)
	);
	plan = $derived(generateSupportPlan(this.points, this.raftPlan.raftedSupportPointIds));

	#nextPointId = 1;
	#onAutoApplied: () => void;

	constructor(
		createAutoSupportWorker?: () => Promise<Worker>,
		onAutoApplied: () => void = () => {}
	) {
		this.#onAutoApplied = onAutoApplied;
		this.autoBuild = new AutoSupportBuild(
			(outcome) => this.#applyAutoSupports(outcome),
			createAutoSupportWorker
		);
	}

	add(hit: ModelSurfaceHit): boolean {
		if (this.autoBuild.status === 'building') return false;
		this.points = [...this.points, this.#createPoint(hit)];
		return true;
	}

	/** Kick off the conservative auto-support scan, unless a set already exists. */
	generateInitial(geometry: AutoSupportBuildInput) {
		if (this.autoDiagnostics !== null || this.points.length > 0) return;
		this.autoBuild.request(geometry);
	}

	reset() {
		this.points = [];
		this.autoDiagnostics = null;
		this.autoGeneratedCount = 0;
		this.#nextPointId = 1;
		this.autoBuild.reset();
	}

	#applyAutoSupports(outcome: AutoSupportOutcome) {
		this.autoDiagnostics = outcome.diagnostics;
		this.points = outcome.hits.map((hit) => this.#createPoint(hit));
		this.autoGeneratedCount = this.points.length;
		this.#onAutoApplied();
	}

	#createPoint(hit: ModelSurfaceHit): SupportPoint {
		return {
			id: `support-point-${this.#nextPointId++}`,
			position: { ...hit.position },
			normal: { ...hit.normal },
			...(hit.lowerContactPosition ? { lowerContactPosition: { ...hit.lowerContactPosition } } : {})
		};
	}
}
