import type { AutoSupportDiagnostics } from '$lib/supports/generate-auto-supports';
import { AutoSupportBuild, type AutoSupportOutcome } from './auto-support-state.svelte';
import {
	areBoundsOutsideBuildVolume,
	findInBoundsZRotation,
	IDENTITY_MODEL_ROTATION,
	modelRotationDegrees,
	transformModelGeometryBounds,
	translateModelBounds
} from './build-volume-renderer/model-transform';
import type {
	BuildVolumeInteractionMode,
	ModelRotation,
	ModelTranslation
} from './build-volume-renderer/types';
import { PreviewBuild } from './preview-state.svelte';
import type { ImportedStlModel } from './stl-importer';
import {
	doesModelProjectionOverlapSupportMargin,
	generateSupportPlan,
	supportFootCenter,
	type ModelSurfaceHit,
	type SupportPoint
} from './supports';
import { generateRaftPlan } from '$lib/supports/raft-plan';

export type WorkflowStep = 'prepare' | 'supports' | 'preview' | 'export';

export type WorkspaceStateOptions = {
	/** Overrides the automatic-support worker factory (tests inject a synchronous stub). */
	createAutoSupportWorker?: () => Promise<Worker>;
};

export class WorkspaceState {
	model = $state.raw<ImportedStlModel | null>(null);
	modelTranslation = $state<ModelTranslation>({ x: 0, y: 0, z: 0 });
	modelRotation = $state<ModelRotation>({ ...IDENTITY_MODEL_ROTATION });
	supportPoints = $state.raw<SupportPoint[]>([]);
	autoSupportDiagnostics = $state.raw<AutoSupportDiagnostics | null>(null);
	autoGeneratedSupportCount = $state(0);
	step = $state<WorkflowStep>('prepare');
	discardSupportsDialogOpen = $state(false);
	raftPlan = $derived(
		generateRaftPlan(
			this.supportPoints
				.filter((point) => !point.lowerContactPosition)
				.map((point) => ({ id: point.id, center: supportFootCenter(point) }))
		)
	);
	supportPlan = $derived(
		generateSupportPlan(this.supportPoints, this.raftPlan.raftedSupportPointIds)
	);
	autoSupportBuild: AutoSupportBuild;
	previewBuild = new PreviewBuild();

	rotatedModelBounds = $derived(
		this.model
			? transformModelGeometryBounds(this.model, { x: 0, y: 0, z: 0 }, this.modelRotation)
			: null
	);
	transformedModelBounds = $derived(
		this.rotatedModelBounds
			? translateModelBounds(this.rotatedModelBounds, this.modelTranslation)
			: null
	);
	modelOutsideBuildVolume = $derived(
		this.transformedModelBounds ? areBoundsOutsideBuildVolume(this.transformedModelBounds) : false
	);
	modelOverlapsSupportMargin = $derived(
		this.transformedModelBounds && !this.modelOutsideBuildVolume
			? doesModelProjectionOverlapSupportMargin(this.transformedModelBounds)
			: false
	);
	canEnterSupports = $derived(this.model !== null && !this.modelOutsideBuildVolume);
	rotationDegrees = $derived(modelRotationDegrees(this.modelRotation));
	transformedDimensions = $derived.by(() => {
		const bounds = this.rotatedModelBounds;
		if (!bounds) return null;
		return {
			x: bounds.max.x - bounds.min.x,
			y: bounds.max.y - bounds.min.y,
			z: bounds.max.z - bounds.min.z
		};
	});
	interactionMode = $derived<BuildVolumeInteractionMode>(
		this.step === 'prepare'
			? 'transform-model'
			: this.step === 'supports'
				? 'place-supports'
				: 'readonly'
	);

	#nextSupportPointId = 1;

	constructor(options: WorkspaceStateOptions = {}) {
		this.autoSupportBuild = new AutoSupportBuild(
			(outcome) => this.#applyAutoSupports(outcome),
			options.createAutoSupportWorker
		);
	}

	setModel(model: ImportedStlModel) {
		this.modelTranslation = { x: 0, y: 0, z: 0 };
		this.modelRotation = findInBoundsZRotation(model);
		this.supportPoints = [];
		this.autoSupportDiagnostics = null;
		this.autoGeneratedSupportCount = 0;
		this.discardSupportsDialogOpen = false;
		this.step = 'prepare';
		this.#nextSupportPointId = 1;
		this.autoSupportBuild.reset();
		this.previewBuild.reset();
		this.model = model;
	}

	setModelTranslation = (translation: ModelTranslation) => {
		if (this.step !== 'prepare') return;
		this.modelTranslation = translation;
	};

	setModelRotation = (rotation: ModelRotation) => {
		if (this.step !== 'prepare') return;
		this.modelRotation = rotation;
	};

	canNavigateTo(step: WorkflowStep): boolean {
		if (step === 'prepare') return true;
		if (step === 'supports' || step === 'preview') return this.canEnterSupports;
		return false;
	}

	requestStep(step: WorkflowStep): boolean {
		if (step === this.step) return true;
		if (!this.canNavigateTo(step)) return false;

		if (
			step === 'prepare' &&
			(this.step === 'supports' || this.step === 'preview') &&
			this.supportPoints.length > 0
		) {
			this.discardSupportsDialogOpen = true;
			return false;
		}

		if (step === 'supports' || step === 'preview') {
			this.#generateInitialSupports();
		} else if (step === 'prepare') {
			// Only reachable with no supports placed yet (the discard dialog guards the
			// rest): cancel an in-flight scan so its draft never lands on the Prepare step.
			this.autoSupportBuild.reset();
		}

		this.step = step;
		if (step === 'preview') this.#requestPreviewBuild();
		return true;
	}

	addSupportPoint(hit: ModelSurfaceHit): boolean {
		if (this.step !== 'supports' || !this.canEnterSupports) return false;
		if (this.autoSupportBuild.status === 'building') return false;
		this.supportPoints = [...this.supportPoints, this.#createSupportPoint(hit)];
		return true;
	}

	cancelDiscardSupports = () => {
		this.discardSupportsDialogOpen = false;
	};

	confirmDiscardSupports = () => {
		this.supportPoints = [];
		this.autoSupportDiagnostics = null;
		this.autoGeneratedSupportCount = 0;
		this.discardSupportsDialogOpen = false;
		this.autoSupportBuild.reset();
		this.previewBuild.reset();
		this.step = 'prepare';
	};

	#generateInitialSupports() {
		if (!this.model) return;
		if (this.autoSupportDiagnostics !== null || this.supportPoints.length > 0) return;
		this.autoSupportBuild.request({
			model: this.model,
			translation: this.modelTranslation,
			rotation: this.modelRotation
		});
	}

	#applyAutoSupports(outcome: AutoSupportOutcome) {
		this.autoSupportDiagnostics = outcome.diagnostics;
		this.supportPoints = outcome.hits.map((hit) => this.#createSupportPoint(hit));
		this.autoGeneratedSupportCount = this.supportPoints.length;
		if (this.step === 'preview') this.#requestPreviewBuild();
	}

	#requestPreviewBuild() {
		if (!this.model || this.modelOutsideBuildVolume) return;
		this.previewBuild.request({
			model: this.model,
			translation: this.modelTranslation,
			rotation: this.modelRotation,
			supportPlan: this.supportPlan,
			raftIslands: this.raftPlan.islands
		});
	}

	#createSupportPoint(hit: ModelSurfaceHit): SupportPoint {
		return {
			id: `support-point-${this.#nextSupportPointId++}`,
			position: { ...hit.position },
			normal: { ...hit.normal },
			...(hit.lowerContactPosition ? { lowerContactPosition: { ...hit.lowerContactPosition } } : {})
		};
	}
}
